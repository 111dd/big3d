#!/usr/bin/env node
/**
 * Injects static (crawlable) portfolio cards into the service pages.
 *
 * - Source of truth: scripts/service-portfolio.json (checked-in snapshot).
 * - Titles are refreshed from the live portfolio API at build time when it is
 *   reachable; on any failure the snapshot titles are used, so the build works
 *   offline / when the API is down.
 * - Images are local repo files rendered through the optimized image pipeline
 *   (js/image-manifest.js), as <picture> with AVIF/WebP sources.
 * - Output is written between the markers below inside each page, so the
 *   script is idempotent and re-runs produce identical HTML for identical
 *   inputs.
 */
const fs = require('fs');
const path = require('path');

const START_MARK = '<!-- service-portfolio:start (generated by scripts/build-service-portfolio.js - do not edit between markers) -->';
const END_MARK = '<!-- service-portfolio:end -->';

const root = path.join(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(__dirname, 'service-portfolio.json'), 'utf8'));

function loadManifest() {
  const src = fs.readFileSync(path.join(root, 'js', 'image-manifest.js'), 'utf8');
  const start = src.indexOf('{');
  const end = src.lastIndexOf('}');
  if (start === -1 || end === -1) throw new Error('Cannot parse js/image-manifest.js');
  return JSON.parse(src.slice(start, end + 1));
}

async function fetchApiTitles(apiUrl) {
  if (typeof fetch !== 'function') return null;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 5000);
  try {
    const res = await fetch(apiUrl, { signal: controller.signal });
    if (!res.ok) return null;
    const projects = await res.json();
    const titles = {};
    for (const p of projects || []) {
      if (p && p.key && p.title) titles[p.key] = String(p.title).trim();
    }
    return titles;
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

function escapeHtml(value) {
  return String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function srcset(entries) {
  return (entries || []).map(e => `${e.url} ${e.width}w`).join(', ');
}

function renderCard(item, manifest, galleryUrl) {
  const entry = manifest[item.image];
  if (!entry) throw new Error(`Image not found in manifest: ${item.image}`);
  const avif = srcset(entry.avif);
  const webp = srcset(entry.webp);
  const fallback = entry.fallback || entry.original;
  const sizes = '(min-width: 832px) 191px, (min-width: 760px) calc((100vw - 68px) / 4), calc((100vw - 42px) / 2)';
  const title = escapeHtml(item.title);
  const alt = escapeHtml(item.alt || item.title);

  return [
    `                <a href="${galleryUrl}" class="service-gallery-card relative block rounded-2xl overflow-hidden shadow-card group" aria-label="${title} - לצפייה בגלריה המלאה">`,
    '                    <picture>',
    avif ? `                        <source type="image/avif" srcset="${avif}" sizes="${sizes}">` : null,
    webp ? `                        <source type="image/webp" srcset="${webp}" sizes="${sizes}">` : null,
    `                        <img src="${fallback}" alt="${alt}" width="400" height="150" style="width:100%;height:150px;max-height:100%;object-fit:contain" loading="lazy" decoding="async" class="w-full h-48 object-cover group-hover:scale-105 transition-transform duration-500">`,
    '                    </picture>',
    '                    <span class="absolute bottom-0 w-full p-3 bg-neutral/90 font-bold text-sm text-gray-100">' + title + '</span>',
    '                </a>'
  ].filter(Boolean).join('\n');
}

function injectIntoPage(pageFile, items, manifest, galleryUrl) {
  const filePath = path.join(root, pageFile);
  const html = fs.readFileSync(filePath, 'utf8');
  const startIdx = html.indexOf(START_MARK);
  const endIdx = html.indexOf(END_MARK);
  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`Markers missing in ${pageFile} - add ${START_MARK} / ${END_MARK}`);
  }

  const cards = items.map(item => renderCard(item, manifest, galleryUrl)).join('\n');
  const gridClass = 'service-gallery-grid';
  const generated = [
    START_MARK,
    `            <div class="${gridClass}">`,
    cards,
    '            </div>',
    '            ' + END_MARK
  ].join('\n');

  const updated = html.slice(0, startIdx) + generated + html.slice(endIdx + END_MARK.length);
  if (updated !== html) fs.writeFileSync(filePath, updated);
  return updated !== html;
}

async function main() {
  const manifest = loadManifest();
  const apiTitles = await fetchApiTitles(config.apiUrl);

  let changed = 0;
  for (const [pageFile, items] of Object.entries(config.pages)) {
    const resolved = items.map(item => ({
      ...item,
      title: (apiTitles && apiTitles[item.key]) || item.title
    }));
    if (injectIntoPage(pageFile, resolved, manifest, config.galleryUrl)) changed += 1;
  }
  console.log(`✅ Service portfolio injected (${Object.keys(config.pages).length} pages, ${changed} updated, API titles: ${apiTitles ? 'live' : 'snapshot'})`);
}

main().catch(err => {
  console.error('❌ build-service-portfolio failed:', err.message);
  process.exit(1);
});
